/// Helper function to get the quarter number for a given surah and ayah.
int getHizbQuarterNumber(int surah, int ayah) {
  for (int i = hizbQuartersData.length - 1; i >= 1; i--) {
    final start = hizbQuartersData[i];
    if (surah > start[0] || (surah == start[0] && ayah >= start[1])) {
      return i;
    }
  }
  return 1;
}
